"""Emit the on-device tutorial cards (drawn by tools/tutorials_claude/build.py) into the firmware.

    python3 tools/tutorials.py

Each card is stored whole, 200 x 200, 1 bit (about 5 KB each), so the device shows exactly the card
the generator drew. The decks are indexed by GameMode (databank.h): League, Competition, Coach, Basic.
"""
import sys
from functools import cache
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

sys.path.insert(0, str(Path(__file__).resolve().parent / "tutorials_claude"))
import build as cards  # noqa: E402
from fontgen import emit_bitmap, logo, screen  # noqa: E402

OUT = Path(__file__).resolve().parents[1] / "firmware/lib/stoprock_ui/src/tutorial_data.cpp"
MODES = ("League", "Competition", "Coach", "Basic")  # the GameMode enum's order


@cache
def font(size, weight="Bold"):
    face = ImageFont.truetype(str(logo.NUNITO), size)
    face.set_variation_by_name(weight)
    return face


def heading():
    """The Tutorials list's heading."""
    image = Image.new("1", (200, 39), 1)
    draw = ImageDraw.Draw(image)
    draw.fontmode = "1"
    screen.text_in_box(draw, "Tutorials", font(30, "ExtraBold"), 0, 200, 0, 39, align="center", fill=0)
    return image


def page_count(mode):
    return len(cards.DECKS[MODES[mode]])


def page_image(mode, page):
    """Card page of the deck for GameMode mode, as the device shows it."""
    return cards.build(MODES[mode], page)


def main():
    lines = [
        "// Generated by tools/tutorials.py from tools/tutorials_claude/build.py. Do not edit by hand.",
        '#include "tutorials.h"',
        "",
        "namespace stoprock {",
        "",
    ]
    emit_bitmap("kTutorialsHeading", heading(), lines)
    for mode, name in enumerate(MODES):
        for page in range(page_count(mode)):
            emit_bitmap(f"kTutorial{name}{page + 1:02d}", page_image(mode, page), lines)
        refs = ", ".join(f"&kTutorial{name}{page + 1:02d}" for page in range(page_count(mode)))
        lines.append(f"static const Bitmap* const kDeck{name}[] = {{{refs}}};")
        lines.append("")
    lines.append("const TutorialDeck kTutorialDecks[] = {")
    for name in MODES:
        lines.append(f"    {{kDeck{name}, sizeof kDeck{name} / sizeof kDeck{name}[0]}},")
    lines.extend(("};", "", "}  // namespace stoprock", ""))
    OUT.write_text("\n".join(lines))
    print("wrote", OUT.relative_to(OUT.parents[3]), f"({OUT.stat().st_size // 1024} KB source)")


if __name__ == "__main__":
    main()
