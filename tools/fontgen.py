"""Generate firmware bitmaps from assets/ so the device draws
exactly what tools/mockups draws.

    python tools/fontgen.py      -> firmware/lib/stoprock_ui/src/assets_data.cpp
"""
from pathlib import Path
import sys

from PIL import Image, ImageDraw

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "tools" / "mockups"))
import logo  # noqa: E402
import screen  # noqa: E402

OUT = ROOT / "firmware" / "lib" / "stoprock_ui" / "src" / "assets_data.cpp"
PAD = 40


def glyph(font, ch):
    """Ink bitmap of ch drawn at (0, 0), its offset from that origin, and its advance."""
    im = Image.new("1", (160, 160), 1)
    d = ImageDraw.Draw(im)
    d.fontmode = "1"
    d.text((PAD, PAD), ch, font=font, fill=0)
    adv = round(font.getlength(ch))
    box = Image.eval(im.convert("L"), lambda v: 255 - v).getbbox()
    if box is None:
        return 0, 0, 0, 0, adv, b""
    l, t, r, b = box
    w, h = r - l, b - t
    rows = []
    for y in range(t, b):
        row = bytearray((w + 7) // 8)
        for x in range(l, r):
            if im.getpixel((x, y)) == 0:
                row[(x - l) // 8] |= 0x80 >> ((x - l) % 8)
        rows.append(bytes(row))
    return l - PAD, t - PAD, w, h, adv, b"".join(rows)


def emit_font(name, font, chars, out):
    glyphs, data = [], bytearray()
    for ch in chars:
        dx, dy, w, h, adv, bits = glyph(font, ch)
        glyphs.append((ord(ch), dx, dy, w, h, adv, len(data)))
        data += bits
    out.append(f"static const uint8_t {name}_bits[] = {{")
    for i in range(0, len(data), 16):
        out.append("    " + ", ".join(f"0x{b:02X}" for b in data[i:i + 16]) + ",")
    out.append("};")
    out.append(f"static const Glyph {name}_glyphs[] = {{")
    for code, dx, dy, w, h, adv, off in glyphs:
        out.append(f"    {{{code}, {dx}, {dy}, {w}, {h}, {adv}, {off}}},")
    out.append("};")
    out.append(f"const Font {name} = {{{name}_glyphs, {name}_bits, {len(glyphs)}}};")
    out.append("")


def emit_bitmap(name, img, out):
    w, h = img.size
    data = bytearray()
    for y in range(h):
        row = bytearray((w + 7) // 8)
        for x in range(w):
            if img.getpixel((x, y)) == 0:
                row[x // 8] |= 0x80 >> (x % 8)
        data += row
    out.append(f"static const uint8_t {name}_bits[] = {{")
    for i in range(0, len(data), 16):
        out.append("    " + ", ".join(f"0x{b:02X}" for b in data[i:i + 16]) + ",")
    out.append("};")
    out.append(f"const Bitmap {name} = {{{name}_bits, {w}, {h}}};")
    out.append("")


def emit_sprite(name, draw, size, out):
    """A small shape drawn by Pillow around the centre (c, c) of a size x size box."""
    c = size // 2
    im = Image.new("1", (size, size), 1)
    d = ImageDraw.Draw(im)
    draw(d, c)
    w = h = size
    data = bytearray()
    for y in range(h):
        row = bytearray((w + 7) // 8)
        for x in range(w):
            if im.getpixel((x, y)) == 0:
                row[x // 8] |= 0x80 >> (x % 8)
        data += row
    out.append(f"static const uint8_t {name}_bits[] = {{")
    for i in range(0, len(data), 16):
        out.append("    " + ", ".join(f"0x{b:02X}" for b in data[i:i + 16]) + ",")
    out.append("};")
    out.append(f"const Sprite {name} = {{{{{name}_bits, {w}, {h}}}, {c}, {c}}};")
    out.append("")


def main():
    f = screen.fonts()
    out = [
        "// Generated by tools/fontgen.py from assets/. Do not edit by hand.",
        "// DSEG7 Classic Bold: SIL OFL 1.1. Spleen: BSD 2-clause. Logo: Nunito Black (SIL OFL 1.1).",
        '#include "assets.h"',
        "",
        "namespace stoprock {",
        "",
    ]
    emit_font("kFontDseg37", f["big"], "0123456789", out)  # the newest stone, at the top
    emit_font("kFontDseg33", f["big_long"], "0123456789", out)  # ... an H2H of 20.00s
    emit_font("kFontDseg24", f["top_small"], "0123456789", out)  # coach page 2's newest stone
    emit_font("kFontDseg16", f["pct"], "0123456789", out)
    ascii_chars = "".join(chr(c) for c in range(32, 127))
    emit_font("kFontSpleen6x12", f["label"], ascii_chars + "°", out)
    # The startup menu uses printable ASCII so new entries can be added without changing the font subset.
    emit_font("kFontMenuTitle", f["menu_title"], ascii_chars, out)
    emit_font("kFontMenuDetail", f["menu_detail"], ascii_chars, out)
    hint = "".join(screen.UNDO_TIP + screen.OFF_TIP + screen.PAGE_TIP + screen.MOVE_HINT)
    hint += "".join(screen.POSITION_NAMES) + "THEM"  # competition's column headers
    emit_font("kFontSpleen12x24", f["hint"], "".join(sorted(set(hint))), out)
    emit_font("kFontSpleen16x32", f["them"], "THEM", out)
    with Image.open(screen.OFF_PAGE_PATH) as off_page:
        if off_page.mode != "1" or off_page.size != (screen.W, screen.H):
            raise ValueError("The off page must be a 200 x 200, 1-bit image")
        emit_bitmap("kOffPage", off_page, out)
    emit_bitmap("kBasicIntro", screen.basic_intro(), out)
    emit_bitmap("kPositionCard", screen.position_card(), out)
    for i, title in enumerate(screen.POSITION_TITLES):
        emit_bitmap(f"kPosition{title}", screen.position_title(i), out)
    out.append("const Bitmap kPositionTitles[] = {"
               + ", ".join("kPosition" + title for title in screen.POSITION_TITLES) + "};")
    out.append("")
    with Image.open(logo.NATIVE_LOGO) as native_logo:
        if native_logo.mode != "1" or native_logo.size != (176, 39):
            raise ValueError("The startup logo must be a 176 x 39, 1-bit image")
        emit_bitmap("kLogo", native_logo, out)
    emit_bitmap("kLogoStrip", logo.strip_logo(), out)  # competition's badge strip, drawn white
    # rocks (radius 5) for league and coach, drawn as tools/mockups/screen.py small_rock()
    emit_sprite("kRockSmall", lambda d, c: d.ellipse([c - 5, c - 5, c + 5, c + 5], outline=0, width=1), 15, out)
    emit_sprite("kCursorSmall", lambda d, c: d.ellipse([c - 5, c - 5, c + 5, c + 5], outline=0, width=3), 15, out)
    emit_sprite("kMadeSmall", lambda d, c: d.ellipse([c - 5, c - 5, c + 5, c + 5], fill=0), 15, out)
    emit_sprite("kMissedSmall", lambda d, c: screen.missed_x(d, c, c), 15, out)
    # the stopwatch shown where a time is awaited: in the large row, and coach page 2's small one
    emit_sprite("kStopwatch", lambda d, c: screen.stopwatch(d, c, c, screen.STOPWATCH_BIG), 31, out)
    emit_sprite("kStopwatchSmall", lambda d, c: screen.stopwatch(d, c, c, screen.STOPWATCH_SMALL), 23, out)
    # Percent-sign slashes: one per possible digit height (the "1" is shorter in DSEG).
    pct = f["pct"]
    boxes = {ch: screen.ink(ch, pct) for ch in "0123456789"}
    heights = sorted({max(boxes[a][3], boxes[b][3]) - min(boxes[a][1], boxes[b][1])
                      for a in boxes for b in boxes})
    names = []
    for dh in heights:
        pw = round(dh * 0.6)
        name = f"kPercentSlash{dh}"
        im = Image.new("1", (pw + 4, dh + 4), 1)
        ImageDraw.Draw(im).line([(2 + pw - 1, 2), (2, 2 + dh - 1)], fill=0, width=2)
        emit_bitmap(name + "_bm", im, out)
        out.append(f"const Sprite {name} = {{{name}_bm, 2, 2}};")
        names.append((dh, name))
    out.append("const PercentSlash kPercentSlashes[] = {")
    for dh, name in names:
        out.append(f"    {{{dh}, &{name}}},")
    out.append("};")
    out.append(f"const uint8_t kPercentSlashCount = {len(names)};")
    out.append("")
    out.append("}  // namespace stoprock")
    OUT.write_text("\n".join(out) + "\n")
    print("wrote", OUT.relative_to(ROOT), f"({OUT.stat().st_size // 1024} KB source)")


if __name__ == "__main__":
    main()
